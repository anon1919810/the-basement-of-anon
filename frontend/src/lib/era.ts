const fmtYear = (y: number, first: boolean, span: boolean): string => {
  if (y < 0) return first ? `公元前${-y}年` : `前${-y}年`;
  if (first) return `公元${y}年`;
  return span ? `公元${y}年` : `${y}年`; // 跨纪元（起点为公元前）→ 结束年补"公元"
};

// 把"时间"字段公元化；已含公元/未匹配的原样返回
export function formatEra(s: string): string {
  if (!s) return s;
  const t = String(s).trim();
  if (!t) return t;
  // 已公元化 / 明显是具体年份 → 不再处理
  if (/公元前|公元|—|－|~|～|-|到/.test(t) && /\d/.test(t)) return t;
  // 匹配朝代关键词
  for (const [kw, name] of KEYWORDS) {
    if (t.includes(kw)) {
      const [a, b] = ERAS[name];
      return `${name}（${fmtYear(a, true, false)}—${fmtYear(b, false, a < 0)}）`;
    }
  }
  return t;
}

// 从文件名推断书名（去扩展名/版本标记）
export function guessBookName(filename: string): string {
  let n = filename.replace(/\.[^.]+$/, ''); // 去扩展名
  // 去常见版本/扫描标记
  n = n
    .replace(/[（(](扫描|清晰版|高清版|OCR|完整版|最终版|修订版)[）)]/gi, '')
    .replace(/[\s_\-]*(扫描版|影印版|电子版|OCR版)[\s_\-]*/gi, '')
    .replace(/[_\-\s]*OCR[_\-\s]*/gi, '') // 裸 OCR 标记（_OCR / OCR_ 等）
    .replace(/[（(]\s*[）)]/g, '') // 删空括号（须在版本标记清理之后）
    .replace(/[【\[]\d+[】\]]/g, '') // 去【123】等序号
    .replace(/[_\-]+/g, ' ')
    .trim();
  return n || filename.replace(/\.[^.]+$/, '');
}
